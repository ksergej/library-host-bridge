CREATE TABLE UBL_TABLES (
    UBL_ID_NUM   BIGINT       GENERATED ALWAYS AS IDENTITY
                  (START WITH 1, INCREMENT BY 1),
    USER_ID       CHAR(10)     ,
    NAME          VARCHAR(100) ,
    REGISTERED_AT TIMESTAMP    ,
    BOOK_ID       CHAR(10)     ,
    TITLE         VARCHAR(200) ,
    AUTHOR        VARCHAR(200),
    STATUS        CHAR(1)      ,
    LOAN_USER_ID       CHAR(10),
    LOAN_BOOK_ID       CHAR(10),
    LOAN_DATE     DATE         ,
    DUE_DATE      DATE         ,
    RETURN_DATE   DATE,
    CONSTRAINT PK_BOOK PRIMARY KEY (UBL_ID_NUM)
);

CREATE VIEW LOAN AS
SELECT
  UBL_ID_NUM as LOAN_ID_NUM,
  LOAN_USER_ID,
  LOAN_BOOK_ID,
  LOAN_DATE,
  DUE_DATE,
  RETURN_DATE
FROM UBL_TABLES
where LOAN_USER_ID is not null
;

CREATE VIEW BOOK AS
SELECT
    BOOK_ID,
    TITLE  ,
    AUTHOR ,
    STATUS
FROM UBL_TABLES
where BOOK_ID is not null
;

create view users as
select
    USER_ID       ,
    NAME          ,
    REGISTERED_AT
from UBL_TABLES
where user_id is not null
;

